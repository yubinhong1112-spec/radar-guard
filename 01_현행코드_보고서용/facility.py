DEMO_NOTE = ''


def to_plan(zone, cx, cz):
    """레이더 좌표(cx, cz) → 도면 좌표(x, y).

    레이더는 천장 하방이므로 (cx, cz) 가 곧 센서 바로 아래를 원점으로 한
    바닥평면 오프셋이다. 설치 위치만 더하면 도면 좌표가 된다.
    레이더가 없는 구역이면 None.
    """
    r = RADARS.get(zone)
    if not r:
        return None
    return (r['pos'][0] + cx, r['pos'][1] + cz)


def coverage(zone):
    """감지영역 사각형 (x, y, w, h). 없으면 None."""
    r = RADARS.get(zone)
    if not r:
        return None
    x, y = r['pos']
    h = COVER_HALF
    return (x - h, y - h, 2 * h, 2 * h)


